//=============================================================================
// 模块名 : transceiver_driver
// 功能   : 字节交换收发器(74xx245 一类)的使能译码
//          根据总线宽度(BS8/BS16)与字节使能(BE3..BE0)产生各段的输出使能
// 项目   : Hamster 1 chipset (M8SBC-486 REV 1.0)
// 原文件 : transceiver_driver.vhd
//
// 说明   : 所有 TR_* 输出均为低有效(0 = 该通路导通)。
//          - 8 位总线周期：把 CPU 的 4 个字节通道合并成 1 个字节通道
//          - 16 位总线周期：把 CPU 的 4 个字节通道合并成 2 个字节通道
//=============================================================================
`timescale 1ns / 1ps

module transceiver_driver (
    input  wire [3:0] BE,          // CPU 字节使能，高有效
    input  wire       BS8,         // 低有效：0 = 8 位总线周期
    input  wire       BS16,        // 低有效：0 = 16 位总线周期

    output wire [3:0] TR_8B,       // 8 位通路使能，低有效
    output wire       TR_16B_LOW,  // 16 位通路低字节使能，低有效
    output wire       TR_16B_HIGH  // 16 位通路高字节使能，低有效
);

    //-------------------------------------------------------------------------
    // 内部译码总线状态
    //-------------------------------------------------------------------------
    wire s_8bit  = (BS8 == 1'b0) && (BS16 == 1'b1);
    wire s_16bit = (BS8 == 1'b1) && (BS16 == 1'b0);

    //-------------------------------------------------------------------------
    // 8 位通路：两种周期下含义不同
    //-------------------------------------------------------------------------
    // 8/16 位周期下，只要最低字节有效就使用通道 0
    assign TR_8B[0] = ~((s_8bit | s_16bit) & ~BE[0]);

    // 仅 8 位周期：BE0 无效而 BE1 有效(奇地址单字节)
    assign TR_8B[1] = ~(s_8bit & BE[0] & ~BE[1]);

    // 两种周期下，BE0、BE1 均无效而 BE2 有效
    assign TR_8B[2] = ~((s_8bit | s_16bit) & BE[0] & BE[1] & ~BE[2]);

    // 仅 8 位周期：只有 BE3 有效(32 位取指的高字节)
    assign TR_8B[3] = ~(s_8bit & BE[0] & BE[1] & BE[2] & ~BE[3]);

    //-------------------------------------------------------------------------
    // 16 位通路：只在 16 位周期有效
    //-------------------------------------------------------------------------
    // 低字节：BE1 有效
    assign TR_16B_LOW  = ~(s_16bit & ~BE[1]);

    // 高字节：BE0、BE1 无效而 BE3 有效
    assign TR_16B_HIGH = ~(s_16bit & BE[0] & BE[1] & ~BE[3]);

endmodule
